  id bigint generated by default as identity primary key,
  requester_id uuid not null references public.bs_profiles(id) on delete cascade,
  addressee_id uuid not null references public.bs_profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','blocked')),
  created_at timestamptz not null default now(),
  unique(requester_id, addressee_id),
  check (requester_id <> addressee_id)
);

create table if not exists public.bs_direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.bs_profiles(id) on delete cascade,
  recipient_id uuid not null references public.bs_profiles(id) on delete cascade,
  text text not null check (char_length(text) between 1 and 1000),
  created_at timestamptz not null default now()
);

