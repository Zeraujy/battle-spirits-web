create or replace function public.bs_search_profiles(search_text text)
returns table(
  id uuid,
  username text,
  display_name text,
  avatar text,
  profile_visibility text,
  relation_status text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.id,
    p.username,
    p.display_name,
    case
      when p.profile_visibility = 'private' and not public.bs_are_friends(auth.uid(), p.id) then null
      else p.avatar
    end as avatar,
    p.profile_visibility,
    coalesce((
      select f.status from public.bs_friendships f
      where (f.requester_id = auth.uid() and f.addressee_id = p.id)
         or (f.requester_id = p.id and f.addressee_id = auth.uid())
      order by f.updated_at desc nulls last, f.created_at desc
      limit 1
    ), 'none') as relation_status
  from public.bs_profiles p
  where p.id <> auth.uid()
    and p.discoverable = true
    and not public.bs_is_blocked(auth.uid(), p.id)
    and (
      p.username ilike '%' || trim(search_text) || '%'
      or p.display_name ilike '%' || trim(search_text) || '%'
    )
  order by p.display_name asc
  limit 20;
$$;

create or replace function public.bs_get_social_profile(target_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  p public.bs_profiles%rowtype;
  can_view boolean;
  is_friend boolean;
begin
  select * into p from public.bs_profiles where id = target_id;
  if not found or public.bs_is_blocked(auth.uid(), target_id) then return null; end if;

  is_friend := public.bs_are_friends(auth.uid(), target_id);
  can_view := auth.uid() = target_id or p.profile_visibility = 'public' or (p.profile_visibility = 'friends' and is_friend);

  return jsonb_build_object(
    'id', p.id,
    'username', p.username,
    'display_name', p.display_name,
    'avatar', case when can_view then p.avatar else null end,
    'banner', case when can_view then p.banner else null end,
    'bio', case when can_view then p.bio else '' end,
    'profile_visibility', p.profile_visibility,
    'is_friend', is_friend,
    'can_message', public.bs_can_message(auth.uid(), target_id),
    'can_view', can_view,
    'show_online_status', case when can_view then p.show_online_status else false end,
    'presence_status', case when can_view and p.show_online_status then p.presence_status else 'hidden' end,
    'last_seen_at', case when can_view and p.show_online_status then p.last_seen_at else null end,
    'show_stats', can_view and p.show_stats,
    'show_decks', can_view and p.show_decks,
    'show_mastery', can_view and p.show_mastery
  );
end;
$$;

create or replace function public.bs_send_friend_request(target_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  policy_value text;
  existing_id bigint;
  reverse_pending bigint;
begin
  if auth.uid() is null then return jsonb_build_object('ok', false, 'error', 'AUTH_REQUIRED'); end if;
  if target_id = auth.uid() then return jsonb_build_object('ok', false, 'error', 'SELF_REQUEST'); end if;
  if public.bs_is_blocked(auth.uid(), target_id) then return jsonb_build_object('ok', false, 'error', 'BLOCKED'); end if;

  select friend_request_policy into policy_value from public.bs_profiles where id = target_id;
  if policy_value is null then return jsonb_build_object('ok', false, 'error', 'PROFILE_NOT_FOUND'); end if;
  if policy_value = 'nobody' then return jsonb_build_object('ok', false, 'error', 'REQUESTS_DISABLED'); end if;
  if policy_value = 'mutuals' and not public.bs_has_mutual_friend(auth.uid(), target_id) then
    return jsonb_build_object('ok', false, 'error', 'MUTUALS_ONLY');
  end if;

  if public.bs_are_friends(auth.uid(), target_id) then
    return jsonb_build_object('ok', true, 'status', 'accepted');
  end if;

  select id into reverse_pending from public.bs_friendships
  where requester_id = target_id and addressee_id = auth.uid() and status = 'pending'
  limit 1;
  if reverse_pending is not null then
    update public.bs_friendships set status='accepted', updated_at=now() where id=reverse_pending;
    return jsonb_build_object('ok', true, 'status', 'accepted');
  end if;

  select id into existing_id from public.bs_friendships
  where requester_id = auth.uid() and addressee_id = target_id
  limit 1;

  if existing_id is null then
    insert into public.bs_friendships(requester_id, addressee_id, status)
    values(auth.uid(), target_id, 'pending');
  else
    update public.bs_friendships set status='pending', updated_at=now() where id=existing_id;
  end if;

  return jsonb_build_object('ok', true, 'status', 'pending');
end;
$$;

create or replace function public.bs_respond_friend_request(request_id bigint, response text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  row_data public.bs_friendships%rowtype;
begin
  select * into row_data from public.bs_friendships where id = request_id and status = 'pending';
  if not found or row_data.addressee_id <> auth.uid() then
    return jsonb_build_object('ok', false, 'error', 'REQUEST_NOT_FOUND');
  end if;

  if response = 'accept' then
    update public.bs_friendships set status='accepted', updated_at=now() where id=request_id;
    return jsonb_build_object('ok', true, 'status', 'accepted');
  elsif response = 'decline' then
    delete from public.bs_friendships where id=request_id;
    return jsonb_build_object('ok', true, 'status', 'declined');
  end if;

  return jsonb_build_object('ok', false, 'error', 'INVALID_RESPONSE');
end;
$$;

