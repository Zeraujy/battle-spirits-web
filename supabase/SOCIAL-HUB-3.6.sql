create or replace function public.bs_notify_friendship()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' and new.status = 'pending' then
    insert into public.bs_notifications(user_id, type, actor_id, payload)
    values(new.addressee_id, 'friend_request', new.requester_id, jsonb_build_object('friendship_id', new.id));
  elsif tg_op = 'UPDATE' and old.status = 'pending' and new.status = 'accepted' then
    insert into public.bs_notifications(user_id, type, actor_id, payload)
    values(new.requester_id, 'friend_accepted', new.addressee_id, jsonb_build_object('friendship_id', new.id));
  end if;
  return new;
end;
$$;

drop trigger if exists bs_friendship_notification_trigger on public.bs_friendships;
create trigger bs_friendship_notification_trigger
after insert or update on public.bs_friendships
for each row execute function public.bs_notify_friendship();

