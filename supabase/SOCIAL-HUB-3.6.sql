create or replace function public.bs_are_friends(a uuid, b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.bs_friendships f
    where f.status = 'accepted'
      and ((f.requester_id = a and f.addressee_id = b)
        or (f.requester_id = b and f.addressee_id = a))
  );
$$;

create or replace function public.bs_is_blocked(a uuid, b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.bs_player_blocks x
    where (x.blocker_id = a and x.blocked_id = b)
       or (x.blocker_id = b and x.blocked_id = a)
  );
$$;

create or replace function public.bs_has_mutual_friend(a uuid, b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  with friends_a as (
    select case when requester_id = a then addressee_id else requester_id end as friend_id
    from public.bs_friendships
    where status = 'accepted' and (requester_id = a or addressee_id = a)
  ), friends_b as (
    select case when requester_id = b then addressee_id else requester_id end as friend_id
    from public.bs_friendships
    where status = 'accepted' and (requester_id = b or addressee_id = b)
  )
  select exists (select 1 from friends_a join friends_b using(friend_id));
$$;

create or replace function public.bs_can_message(sender uuid, recipient uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    sender = recipient
    or (
      not public.bs_is_blocked(sender, recipient)
      and exists (
        select 1 from public.bs_profiles p
        where p.id = recipient
          and (
            p.message_policy = 'everyone'
            or (p.message_policy = 'friends' and public.bs_are_friends(sender, recipient))
          )
      )
    );
$$;

