$$;

create or replace function public.bs_block_user(target_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if target_id = auth.uid() then return false; end if;
  insert into public.bs_player_blocks(blocker_id, blocked_id)
  values(auth.uid(), target_id)
  on conflict do nothing;
  delete from public.bs_friendships
  where (requester_id = auth.uid() and addressee_id = target_id)
     or (requester_id = target_id and addressee_id = auth.uid());
  return true;
end;
$$;

create or replace function public.bs_unblock_user(target_id uuid)
returns boolean
language sql
security definer
set search_path = public
as $$
  delete from public.bs_player_blocks where blocker_id = auth.uid() and blocked_id = target_id;
  select true;
$$;

drop function if exists public.bs_list_friends();
create function public.bs_list_friends()
returns table(
  friend_id uuid,
  username text,
  display_name text,
  avatar text,
  bio text,
  presence_status text,
  is_online boolean,
  last_seen_at timestamptz,
  unread_count bigint
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.id,
    p.username,
    p.display_name,
    case when p.profile_visibility = 'private' then null else p.avatar end,
    case when p.profile_visibility <> 'private' then p.bio else '' end,
    case when p.show_online_status then p.presence_status else 'hidden' end,
    case when p.show_online_status and p.presence_status <> 'invisible' and p.last_seen_at > now() - interval '2 minutes' then true else false end,
    case when p.show_online_status then p.last_seen_at else null end,
    (select count(*) from public.bs_direct_messages m where m.sender_id = p.id and m.recipient_id = auth.uid() and m.read_at is null)
  from public.bs_friendships f
  join public.bs_profiles p on p.id = case when f.requester_id = auth.uid() then f.addressee_id else f.requester_id end
  where f.status = 'accepted'
    and (f.requester_id = auth.uid() or f.addressee_id = auth.uid())
    and not public.bs_is_blocked(auth.uid(), p.id)
  order by 7 desc, p.display_name asc;
$$;

