create or replace function public.bs_craft_value(p_rarity text)
returns integer language sql immutable as $$
  select case upper(coalesce(p_rarity,'C'))
    when 'C' then 5 when 'U' then 10 when 'R' then 20 when 'M' then 40
    when 'X' then 80 when 'XX' then 120 when 'CP' then 50 when 'CX' then 100
    when 'TX' then 100 when 'PX' then 120 else 5 end;
$$;

create or replace function public.bs_grant_card_copy(p_user uuid, p_card_id text, p_rarity text, p_reason text)
returns jsonb
language plpgsql security definer set search_path=public as $$
declare
  v_before integer := 0;
  v_after integer := 0;
  v_craft integer := 0;
  v_accepted boolean := false;
begin
  select quantity into v_before from public.bs_player_cards
   where user_id=p_user and card_id=p_card_id for update;
  v_before := coalesce(v_before,0);
  v_accepted := v_before < 6;
  if v_accepted then
    v_after := v_before + 1;
    insert into public.bs_player_cards(user_id,card_id,quantity,updated_at)
      values(p_user,p_card_id,v_after,now())
      on conflict(user_id,card_id) do update set quantity=excluded.quantity, updated_at=now();
  else
    v_after := v_before;
  end if;

  if v_before > 0 then
    v_craft := public.bs_craft_value(p_rarity);
    update public.bs_player_wallets set craft_coins=craft_coins+v_craft,updated_at=now() where user_id=p_user;
    insert into public.bs_economy_ledger(user_id,currency,amount,reason)
      values(p_user,'craft',v_craft,p_reason || ':duplicate:' || p_card_id);
  end if;

  return jsonb_build_object('cardId',p_card_id,'rarity',p_rarity,'before',v_before,'after',v_after,
    'accepted',v_accepted,'duplicate',v_before>0,'overflow',not v_accepted,'craftAwarded',v_craft);
end;
$$;

create or replace function public.bs_purchase_shop_product(p_product_id text, p_quantity integer default 1)
returns jsonb
language plpgsql security definer set search_path=public as $$
declare
  v_user uuid := auth.uid();
  v_product public.bs_shop_products%rowtype;
  v_wallet bigint;
  v_total bigint;
  v_pack integer;
  v_slot integer;
  v_copy integer;
  v_card record;
  v_grants jsonb := '[]'::jsonb;
  v_event jsonb;
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_quantity < 1 or p_quantity > 20 then raise exception 'INVALID_QUANTITY'; end if;
  select * into v_product from public.bs_shop_products where product_id=p_product_id and enabled=true;
  if not found then raise exception 'PRODUCT_UNAVAILABLE'; end if;

  insert into public.bs_player_wallets(user_id) values(v_user) on conflict(user_id) do nothing;
  insert into public.bs_player_progress(user_id) values(v_user) on conflict(user_id) do nothing;
  select spirit_coins into v_wallet from public.bs_player_wallets where user_id=v_user for update;
  v_total := v_product.spirit_price::bigint * p_quantity::bigint;
  if v_wallet < v_total then raise exception 'INSUFFICIENT_SPIRIT_COINS'; end if;
  update public.bs_player_wallets set spirit_coins=spirit_coins-v_total,updated_at=now() where user_id=v_user;
  insert into public.bs_economy_ledger(user_id,currency,amount,reason)
    values(v_user,'spirit',-v_total,'shop_purchase:'||p_product_id);

  if v_product.category='boosters' then
    for v_pack in 1..p_quantity loop
      for v_slot in 1..coalesce(v_product.pack_size,8) loop
        select p.card_id,p.rarity into v_card from public.bs_shop_pool_cards p
          where p.product_id=p_product_id
          order by (-ln(greatest(random(),0.000000001))) /
            (case upper(p.rarity) when 'C' then 60 when 'U' then 28 when 'R' then 9 when 'M' then 2.5
             when 'X' then .45 when 'XX' then .08 when 'CP' then 1.5 when 'CX' then .3 when 'TX' then .3 when 'PX' then .15 else 1 end)
          limit 1;
        if v_card.card_id is null then raise exception 'EMPTY_PRODUCT_POOL'; end if;
        v_event := public.bs_grant_card_copy(v_user,v_card.card_id,v_card.rarity,'booster_open:'||p_product_id);
        v_grants := v_grants || jsonb_build_array(v_event);
      end loop;
    end loop;
  elsif v_product.category='decks' then
    for v_copy in 1..p_quantity loop
      for v_card in select card_id,quantity,rarity from public.bs_shop_deck_cards where product_id=p_product_id loop
        for v_slot in 1..v_card.quantity loop
          v_event := public.bs_grant_card_copy(v_user,v_card.card_id,v_card.rarity,'deck_purchase:'||p_product_id);
          v_grants := v_grants || jsonb_build_array(v_event);
        end loop;
      end loop;
    end loop;
    if v_product.recipe_id is not null then
      insert into public.bs_player_deck_recipes(user_id,recipe_id) values(v_user,v_product.recipe_id)
      on conflict(user_id,recipe_id) do nothing;
    end if;
  end if;

  return jsonb_build_object('ok',true,'productId',p_product_id,'quantity',p_quantity,'totalPrice',v_total,
    'recipeId',v_product.recipe_id,'grants',v_grants);
end;
$$;

create or replace function public.bs_claim_starter_decks(p_product_ids text[])
returns jsonb
language plpgsql security definer set search_path=public as $$
declare
  v_user uuid := auth.uid();
  v_progress public.bs_player_progress%rowtype;
  v_product_id text;
  v_product public.bs_shop_products%rowtype;
  v_card record;
  v_i integer;
  v_event jsonb;
  v_grants jsonb := '[]'::jsonb;
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if cardinality(p_product_ids) <> 3 or (select count(distinct x) from unnest(p_product_ids) x) <> 3 then
    raise exception 'SELECT_EXACTLY_THREE';
  end if;
  insert into public.bs_player_wallets(user_id) values(v_user) on conflict(user_id) do nothing;
  insert into public.bs_player_progress(user_id) values(v_user) on conflict(user_id) do nothing;
  select * into v_progress from public.bs_player_progress where user_id=v_user for update;
  if v_progress.onboarding_complete then
    return jsonb_build_object('ok',true,'alreadyComplete',true);
  end if;

  foreach v_product_id in array p_product_ids loop
    select * into v_product from public.bs_shop_products
      where product_id=v_product_id and category='decks' and enabled=true and starter_eligible=true;
    if not found then raise exception 'INVALID_STARTER_DECK'; end if;
    if not exists(select 1 from public.bs_shop_deck_cards where product_id=v_product_id) then raise exception 'DECK_DATA_INCOMPLETE'; end if;
    for v_card in select card_id,quantity,rarity from public.bs_shop_deck_cards where product_id=v_product_id loop
      for v_i in 1..v_card.quantity loop
        v_event := public.bs_grant_card_copy(v_user,v_card.card_id,v_card.rarity,'starter_deck:'||v_product_id);
        v_grants := v_grants || jsonb_build_array(v_event);
      end loop;
    end loop;
    insert into public.bs_player_deck_recipes(user_id,recipe_id) values(v_user,v_product.recipe_id)
      on conflict(user_id,recipe_id) do nothing;
  end loop;

  update public.bs_player_progress set onboarding_complete=true,starter_deck_ids=p_product_ids,updated_at=now() where user_id=v_user;
  return jsonb_build_object('ok',true,'starterDeckIds',p_product_ids,'grants',v_grants);
end;
$$;

create or replace function public.bs_claim_account_creation_bundle(
  p_guest_spirit bigint default 0,
  p_guest_craft bigint default 0,
  p_collection jsonb default '[]'::jsonb,
  p_recipes text[] default '{}',
  p_onboarding_complete boolean default false,
  p_starter_deck_ids text[] default '{}'
)
returns jsonb
language plpgsql security definer set search_path=public as $$
declare
  v_user uuid := auth.uid();
  v_progress public.bs_player_progress%rowtype;
  v_entry jsonb;
  v_card_id text;
  v_qty integer;
  v_recipe text;
  v_spirit bigint := least(greatest(coalesce(p_guest_spirit,0),0),1000000);
  v_craft bigint := least(greatest(coalesce(p_guest_craft,0),0),1000000);
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  insert into public.bs_player_wallets(user_id) values(v_user) on conflict(user_id) do nothing;
  insert into public.bs_player_progress(user_id) values(v_user) on conflict(user_id) do nothing;
  select * into v_progress from public.bs_player_progress where user_id=v_user for update;
  if v_progress.account_creation_bonus_claimed then
    return jsonb_build_object('ok',true,'alreadyClaimed',true);
  end if;
  if not v_progress.account_creation_bonus_eligible then
    raise exception 'ACCOUNT_CREATION_BONUS_NOT_ELIGIBLE';
  end if;

  update public.bs_player_wallets set
    spirit_coins=spirit_coins+v_spirit+1500,
    craft_coins=craft_coins+v_craft+1500,
    updated_at=now()
  where user_id=v_user;

  insert into public.bs_economy_ledger(user_id,currency,amount,reason,source_uid)
    values(v_user,'spirit',v_spirit+1500,'AccountCreationBonus','account-creation-bonus-spirit')
    on conflict do nothing;
  insert into public.bs_economy_ledger(user_id,currency,amount,reason,source_uid)
    values(v_user,'craft',v_craft+1500,'AccountCreationBonus','account-creation-bonus-craft')
    on conflict do nothing;

  for v_entry in select value from jsonb_array_elements(coalesce(p_collection,'[]'::jsonb)) loop
    v_card_id := trim(coalesce(v_entry->>'cardId',v_entry->>'card_id',''));
    v_qty := least(greatest(coalesce((v_entry->>'quantity')::integer,0),0),6);
    if v_card_id <> '' and v_qty > 0 then
      insert into public.bs_player_cards(user_id,card_id,quantity,updated_at)
        values(v_user,v_card_id,v_qty,now())
        on conflict(user_id,card_id) do update set quantity=greatest(public.bs_player_cards.quantity,excluded.quantity),updated_at=now();
    end if;
  end loop;

  foreach v_recipe in array coalesce(p_recipes,'{}') loop
    if trim(v_recipe) <> '' then
      insert into public.bs_player_deck_recipes(user_id,recipe_id) values(v_user,v_recipe)
        on conflict(user_id,recipe_id) do nothing;
    end if;
  end loop;

  update public.bs_player_progress set
    onboarding_complete = onboarding_complete or coalesce(p_onboarding_complete,false),
    starter_deck_ids = case when cardinality(coalesce(p_starter_deck_ids,'{}')) > 0 then p_starter_deck_ids else starter_deck_ids end,
    account_creation_bonus_claimed=true,
    account_creation_bonus_eligible=false,
    updated_at=now()
  where user_id=v_user;

  return jsonb_build_object('ok',true,'bonusSpirit',1500,'bonusCraft',1500,'migratedSpirit',v_spirit,'migratedCraft',v_craft);
end;
$$;

create or replace function public.bs_create_economy_progress()
returns trigger
language plpgsql security definer set search_path=public as $$
begin
  insert into public.bs_player_progress(user_id,account_creation_bonus_eligible)
    values(new.id,true)
    on conflict(user_id) do update set account_creation_bonus_eligible=true,updated_at=now();
  return new;
end;
$$;

drop trigger if exists bs_auth_create_economy_progress on auth.users;
create trigger bs_auth_create_economy_progress
after insert on auth.users
for each row execute function public.bs_create_economy_progress();

create or replace function public.bs_ensure_economy_account()
returns void language plpgsql security definer set search_path=public as $$
begin
  if auth.uid() is null then return; end if;
  insert into public.bs_player_wallets(user_id) values(auth.uid()) on conflict(user_id) do nothing;
  insert into public.bs_player_progress(user_id) values(auth.uid()) on conflict(user_id) do nothing;
end;
$$;

