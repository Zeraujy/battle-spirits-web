begin;

alter table public.bs_player_cards drop constraint if exists bs_player_cards_quantity_max6;
alter table public.bs_player_cards add constraint bs_player_cards_quantity_max6 check (quantity between 0 and 6);

create table if not exists public.bs_player_deck_recipes (
  user_id uuid not null references auth.users(id) on delete cascade,
  recipe_id text not null,
  acquired_at timestamptz not null default now(),
  primary key (user_id, recipe_id)
);

create table if not exists public.bs_player_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  onboarding_complete boolean not null default false,
  starter_deck_ids text[] not null default '{}',
  account_creation_bonus_claimed boolean not null default false,
  account_creation_bonus_eligible boolean not null default false,
  updated_at timestamptz not null default now()
);

alter table public.bs_player_progress
  add column if not exists account_creation_bonus_eligible boolean not null default false;

create table if not exists public.bs_shop_products (
  product_id text primary key,
  category text not null check (category in ('boosters','decks')),
  set_code text not null,
  spirit_price integer not null check (spirit_price >= 0),
  pack_size integer,
  recipe_id text,
  starter_eligible boolean not null default false,
  enabled boolean not null default true
);

create table if not exists public.bs_shop_pool_cards (
  product_id text not null references public.bs_shop_products(product_id) on delete cascade,
  card_id text not null,
  rarity text not null default 'C',
  primary key (product_id, card_id)
);

create table if not exists public.bs_shop_deck_cards (
  product_id text not null references public.bs_shop_products(product_id) on delete cascade,
  card_id text not null,
  quantity integer not null check (quantity > 0),
  rarity text not null default 'C',
  primary key (product_id, card_id)
);

alter table public.bs_player_deck_recipes enable row level security;
alter table public.bs_player_progress enable row level security;
alter table public.bs_shop_products enable row level security;
alter table public.bs_shop_pool_cards enable row level security;
alter table public.bs_shop_deck_cards enable row level security;

drop policy if exists "Players can read own recipes" on public.bs_player_deck_recipes;
create policy "Players can read own recipes" on public.bs_player_deck_recipes for select using (auth.uid() = user_id);
drop policy if exists "Players can read own progress" on public.bs_player_progress;
create policy "Players can read own progress" on public.bs_player_progress for select using (auth.uid() = user_id);

