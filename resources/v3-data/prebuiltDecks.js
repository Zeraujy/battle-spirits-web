function quantityOf(card) {
  const value = Number(card?.includedQuantity || 0);
  return Number.isFinite(value) && value > 0 ? value : 0;
}

function belongsToSet(card, setCode) {
  const code = String(setCode || "").trim().toUpperCase();
  const declaredSet = String(card?.set || card?.setCode || card?.product || "")
    .trim()
    .toUpperCase();
  const id = String(card?.id || "").trim().toUpperCase();

  return declaredSet === code || id.startsWith(`${code}-`);
}

function explicitEntries(template) {
  if (!Array.isArray(template?.cards) || template.cards.length === 0) {
    return null;
  }

  const unique = new Map();

  for (const raw of template.cards) {
    const cardId = String(raw?.cardId || raw?.id || "").trim();
    const quantity = Number(raw?.quantity || 0);

    if (!cardId || !Number.isFinite(quantity) || quantity <= 0) {
      continue;
    }

    unique.set(cardId, {
      cardId,
      quantity
    });
  }

  return [...unique.values()];
}

export function buildPrebuiltDeck(template, cards, cardIndex) {
  const explicit = explicitEntries(template);
  let entries;

  if (explicit) {
    entries = explicit;
  } else {
    const uniqueEntries = new Map();

    for (const card of cards || []) {
      if (!belongsToSet(card, template.setCode)) continue;

      const quantity = quantityOf(card);
      if (!quantity || !card?.id) continue;

      uniqueEntries.set(String(card.id), {
        cardId: String(card.id),
        quantity
      });
    }

    entries = [...uniqueEntries.values()];
  }

  entries = entries.sort((a, b) =>
    a.cardId.localeCompare(b.cardId, undefined, { numeric: true })
  );

  const totalCards = entries.reduce(
    (sum, entry) => sum + Number(entry.quantity || 0),
    0
  );

  const missingCardIds = entries
    .filter((entry) => !cardIndex?.get?.(entry.cardId))
    .map((entry) => entry.cardId);

  const expectedSize = Number(template.expectedSize || 40);
  const cover =
    cardIndex?.get?.(template.coverCardId) ||
    cardIndex?.get?.(entries[0]?.cardId) ||
    null;

  return {
    entries,
    totalCards,
    uniqueCards: entries.length,
    missingCardIds,
    cover,
    ready:
      entries.length > 0 &&
      totalCards === expectedSize &&
      missingCardIds.length === 0
  };
}
